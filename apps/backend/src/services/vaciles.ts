/**
 * Vaciles desde el panel (§9-sexies del CLAUDE.md, 6-nov-2026).
 *
 * Los vaciles de siempre van DIBUJADOS dentro de la app: los Clásicos (ids 1
 * a 10) y los de Halloween (101 a 110), y cada tanda nueva obligaba a sacar
 * versión. Iban: pasar una tanda nueva y que salga en una pestaña nueva del
 * selector sin tocar las tiendas. Una pestaña de aquí es un nombre y sus
 * mensajes, y es de uno de dos TIPOS:
 *
 *   - 'texto': una lista de frases, una por línea; la app pinta cada una en
 *     una tarjeta de CORRR (negro y naranja).
 *   - 'imagen': parejas de carteles PNG (provocación + respuesta, 592×1280,
 *     el mismo formato que los clásicos), subidos desde el panel o con
 *     scripts/subir-vaciles.mjs. El servidor los guarda en la base de datos,
 *     les hace la miniatura (288×512 JPG, como las `-v.jpg` de la app) y los
 *     sirve con caché larga. El texto de cada uno es su nombre: si a un móvil
 *     no le llega el dibujo, enseña la tarjeta con ese nombre, nunca un hueco.
 *
 * Los identificadores de los mensajes empiezan en 1001 A PROPÓSITO: el id
 * viaja en la fila de `taunts` y la app de quien lo recibe lo busca primero en
 * sus catálogos dibujados. Si se solaparan con el 1-10 o el 101-110, a quien
 * lo recibiera le saldría el dibujo de ese número en vez del nuestro.
 *
 * Nada se borra de verdad: un mensaje quitado de la lista se APAGA (`activo`)
 * y una pestaña eliminada se marca (`borrada`). Un vacile ya enviado sigue
 * teniendo su texto y su cartel cuando el otro abra la app, aunque la pestaña
 * ya no exista.
 */
import { createHash } from 'node:crypto';
import sharp from 'sharp';

type Db = { query: (sql: string, params?: any[]) => Promise<{ rows: any[] }> };

/** El primer id de un mensaje del panel. Por debajo están los dibujados. */
export const PRIMER_ID_VACILE = 1001;
/** Tope de mensajes por pestaña y tipo, y de letras por mensaje. En la app el
 *  texto se encoge hasta caber en la tarjeta: más de esto no se lee. */
export const MAX_MENSAJES_VACILE = 50;
export const MAX_LETRAS_VACILE = 140;
export const MAX_NOMBRE_PESTANA = 18;
/** Los carteles: el mismo formato que los clásicos de la app. */
export const CARTEL_ANCHO = 592;
export const CARTEL_ALTO = 1280;
export const MINIATURA_ANCHO = 288;
export const MINIATURA_ALTO = 512;
/** Dónde se sirven los carteles (`<id>.png`) y sus miniaturas (`<id>-v.jpg`). */
export const RUTA_IMAGEN_VACILE = '/vaciles/imagen/';

export type TipoPestana = 'texto' | 'imagen';
export type MensajeVacile = {
  id: number;
  texto: string;
  /** Solo en las pestañas de imágenes: el cartel y su miniatura, con `?v=`
   *  para que al cambiarlo nadie se quede con el viejo. */
  imagen?: string;
  miniatura?: string;
};
export type PestanaVacile = {
  id: number;
  nombre: string;
  orden: number;
  tipo: TipoPestana;
  /** 'no' / 'si' / 'prueba:Nombre1,Nombre2', como las campañas y Halloween. */
  modo: string;
  mensajes: MensajeVacile[];
  respuestas: MensajeVacile[];
};

export async function prepararVaciles(db: Db): Promise<void> {
  await db.query(`
    CREATE TABLE IF NOT EXISTS vacile_pestanas (
      id SERIAL PRIMARY KEY,
      nombre TEXT NOT NULL,
      orden INT NOT NULL DEFAULT 0,
      modo TEXT NOT NULL DEFAULT 'no',
      borrada BOOLEAN NOT NULL DEFAULT FALSE,
      creada_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await db.query(`ALTER TABLE vacile_pestanas ADD COLUMN IF NOT EXISTS tipo TEXT NOT NULL DEFAULT 'texto'`);
  await db.query(`
    CREATE TABLE IF NOT EXISTS vacile_mensajes (
      id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH ${PRIMER_ID_VACILE}),
      pestana_id INT NOT NULL REFERENCES vacile_pestanas(id) ON DELETE CASCADE,
      tipo TEXT NOT NULL DEFAULT 'mensaje',
      texto TEXT NOT NULL,
      orden INT NOT NULL DEFAULT 0,
      activo BOOLEAN NOT NULL DEFAULT TRUE,
      creado_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await db.query(`CREATE INDEX IF NOT EXISTS vacile_mensajes_pestana_idx ON vacile_mensajes(pestana_id, tipo) WHERE activo`);
  // Los carteles van en la base de datos (medio MB cada uno, son pocos) y se
  // sirven desde memoria: igual que los logos de las campañas.
  await db.query(`
    CREATE TABLE IF NOT EXISTS vacile_imagenes (
      mensaje_id INT PRIMARY KEY REFERENCES vacile_mensajes(id) ON DELETE CASCADE,
      png BYTEA NOT NULL,
      jpg BYTEA NOT NULL,
      version TEXT NOT NULL,
      subido_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
}

/** Lo que se pega en el panel, una línea por mensaje: sin líneas vacías, sin
 *  espacios de más, sin repetidos y con tope. También vale una lista. */
export function lineasDeVaciles(entrada: unknown): string[] {
  const crudo = Array.isArray(entrada) ? entrada.map(x => String(x ?? '')) : String(entrada ?? '').split(/\r?\n/);
  const vistas = new Set<string>();
  const limpias: string[] = [];
  for (const linea of crudo) {
    const texto = linea.replace(/\s+/g, ' ').trim().slice(0, MAX_LETRAS_VACILE).trim();
    if (!texto) continue;
    const clave = texto.toLowerCase();
    if (vistas.has(clave)) continue;
    vistas.add(clave);
    limpias.push(texto);
  }
  return limpias.slice(0, MAX_MENSAJES_VACILE);
}

/** El nombre de un cartel a partir del archivo: `03_01_PROVOCACION_sombra_azul.png`
 *  (los tótems) o `03_PROVOCACION_azul_hablas_mucho.png` (Aura) → número 3,
 *  'provocacion', «sombra azul». null si el nombre no sigue el patrón. El
 *  panel lleva esta misma expresión en su JavaScript. */
export function parteDeCartel(archivo: string): { numero: number; cual: 'provocacion' | 'respuesta'; nombre: string } | null {
  const m = /^(\d+)(?:[_-]0?[12])?[_-](PROVOCACION|RESPUESTA)[_-](.+)\.png$/i.exec(archivo.trim());
  if (!m) return null;
  return {
    numero: Number(m[1]),
    cual: m[2].toUpperCase() === 'PROVOCACION' ? 'provocacion' : 'respuesta',
    nombre: m[3].replace(/[_-]+/g, ' ').trim(),
  };
}

/** Busca (o revive, o crea) la fila de un mensaje por su texto, sin cambiar
 *  el id de la que ya está: el id es lo que viaja en cada vacile enviado. */
async function filaDeMensaje(db: Db, pestanaId: number, tipo: 'mensaje' | 'respuesta', texto: string, orden: number): Promise<number> {
  const { rows: activa } = await db.query(
    `SELECT id FROM vacile_mensajes WHERE pestana_id = $1 AND tipo = $2 AND activo AND LOWER(texto) = LOWER($3)
      ORDER BY id LIMIT 1`,
    [pestanaId, tipo, texto],
  );
  if (activa[0]) {
    await db.query('UPDATE vacile_mensajes SET orden = $2, texto = $3 WHERE id = $1', [activa[0].id, orden, texto]);
    return Number(activa[0].id);
  }
  const { rows: apagada } = await db.query(
    `SELECT id FROM vacile_mensajes
      WHERE pestana_id = $1 AND tipo = $2 AND NOT activo AND LOWER(texto) = LOWER($3)
      ORDER BY id LIMIT 1`,
    [pestanaId, tipo, texto],
  );
  if (apagada[0]) {
    await db.query('UPDATE vacile_mensajes SET activo = TRUE, orden = $2, texto = $3 WHERE id = $1', [apagada[0].id, orden, texto]);
    return Number(apagada[0].id);
  }
  const { rows } = await db.query(
    'INSERT INTO vacile_mensajes (pestana_id, tipo, texto, orden) VALUES ($1, $2, $3, $4) RETURNING id',
    [pestanaId, tipo, texto, orden],
  );
  return Number(rows[0].id);
}

/** Deja los mensajes de un tipo de una pestaña como dice la lista, sin cambiar
 *  el id de los que siguen. Un texto que se quita se apaga; si vuelve a
 *  escribirse, revive con su id. */
async function sincronizarMensajes(db: Db, pestanaId: number, tipo: 'mensaje' | 'respuesta', textos: string[]): Promise<void> {
  const { rows: antes } = await db.query(
    'SELECT id FROM vacile_mensajes WHERE pestana_id = $1 AND tipo = $2 AND activo',
    [pestanaId, tipo],
  );
  const seQuedan = new Set<number>();
  for (let i = 0; i < textos.length; i++) {
    seQuedan.add(await filaDeMensaje(db, pestanaId, tipo, textos[i], i));
  }
  for (const r of antes) {
    if (!seQuedan.has(Number(r.id))) {
      await db.query('UPDATE vacile_mensajes SET activo = FALSE WHERE id = $1', [r.id]);
    }
  }
}

export async function guardarPestanaVaciles(db: Db, entrada: {
  id: number | null;
  nombre: string;
  orden: number;
  modo: string;
  tipo?: TipoPestana;
  mensajes: string[];
  respuestas: string[];
}): Promise<PestanaVacile> {
  const nombre = entrada.nombre.replace(/\s+/g, ' ').trim().slice(0, MAX_NOMBRE_PESTANA).trim();
  if (!nombre) throw new Error('Falta el nombre de la pestaña');
  const tipo: TipoPestana = entrada.tipo === 'imagen' ? 'imagen' : 'texto';
  if (tipo === 'texto' && entrada.mensajes.length === 0) throw new Error('Pon al menos un mensaje, uno por línea');
  const orden = Number.isFinite(entrada.orden) ? Math.round(entrada.orden) : 0;
  let id = entrada.id;
  if (id !== null) {
    const { rows } = await db.query(
      'UPDATE vacile_pestanas SET nombre = $2, orden = $3, modo = $4, tipo = $5 WHERE id = $1 AND NOT borrada RETURNING id',
      [id, nombre, orden, entrada.modo, tipo],
    );
    if (!rows[0]) throw new Error('Esa pestaña ya no existe');
  } else {
    const { rows } = await db.query(
      'INSERT INTO vacile_pestanas (nombre, orden, modo, tipo) VALUES ($1, $2, $3, $4) RETURNING id',
      [nombre, orden, entrada.modo, tipo],
    );
    id = Number(rows[0].id);
  }
  // En una pestaña de imágenes los mensajes los ponen y quitan los carteles
  // (guardarParejaVacile / quitarParejaVacile): guardar el nombre o el
  // interruptor no los toca.
  if (tipo === 'texto') {
    await sincronizarMensajes(db, id, 'mensaje', entrada.mensajes);
    await sincronizarMensajes(db, id, 'respuesta', entrada.respuestas);
  }
  const guardada = (await pestanasVacilesAdmin(db)).find(p => p.id === id);
  if (!guardada) throw new Error('No se ha podido guardar la pestaña');
  return guardada;
}

/** Cambia SOLO el interruptor de una pestaña (apagada, en prueba o encendida),
 *  sin tocar nombre, orden ni mensajes: es el botón de su cabecera en el panel.
 *  Devuelve el modo guardado ('no', 'si' o 'prueba:A,B'). */
export async function cambiarModoPestanaVaciles(db: Db, id: number, modo: string): Promise<string> {
  const { rows } = await db.query(
    'UPDATE vacile_pestanas SET modo = $2 WHERE id = $1 AND NOT borrada RETURNING modo',
    [id, modo],
  );
  if (!rows[0]) throw new Error('Esa pestaña ya no existe');
  return String(rows[0].modo);
}

/** Comprueba que es una imagen y la deja en PNG del tamaño de los carteles
 *  (592×1280, encajada sobre negro si no viene exacta), con su miniatura JPG. */
async function prepararCartel(entrada: Buffer): Promise<{ png: Buffer; jpg: Buffer; version: string }> {
  let png: Buffer;
  let jpg: Buffer;
  try {
    const meta = await sharp(entrada, { failOn: 'none' }).metadata();
    const yaBien = meta.format === 'png' && meta.width === CARTEL_ANCHO && meta.height === CARTEL_ALTO;
    png = yaBien ? entrada : await sharp(entrada, { failOn: 'none' })
      .resize(CARTEL_ANCHO, CARTEL_ALTO, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 1 } })
      .png()
      .toBuffer();
    jpg = await sharp(png, { failOn: 'none' })
      .resize(MINIATURA_ANCHO, MINIATURA_ALTO, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 1 } })
      .jpeg({ quality: 82 })
      .toBuffer();
  } catch {
    throw new Error('Esa imagen no se puede leer. Tiene que ser un PNG (o un JPG)');
  }
  return { png, jpg, version: createHash('sha1').update(png).digest('hex').slice(0, 10) };
}

/** Lo servido, en memoria del proceso: cada cartel se lee de la base de datos
 *  una vez por despliegue y no en cada petición (cuota de salida de Supabase). */
const cartelesEnMemoria = new Map<number, { png: Buffer; jpg: Buffer; version: string }>();

/** Una pareja de carteles (provocación + respuesta) de una pestaña de imágenes.
 *  El «texto» de los dos mensajes es el nombre de la pareja: es lo que ve
 *  quien no consiga bajar el dibujo. Si la pareja ya existía (mismo nombre),
 *  se cambian los carteles y los ids se quedan. */
export async function guardarParejaVacile(db: Db, entrada: {
  pestanaId: number;
  orden: number;
  nombre: string;
  provocacion: Buffer;
  respuesta: Buffer;
}): Promise<{ mensajeId: number; respuestaId: number }> {
  const nombre = entrada.nombre.replace(/[_\s]+/g, ' ').trim().slice(0, MAX_LETRAS_VACILE).trim();
  if (!nombre) throw new Error('Falta el nombre de la pareja de carteles');
  const { rows } = await db.query('SELECT tipo FROM vacile_pestanas WHERE id = $1 AND NOT borrada', [entrada.pestanaId]);
  if (!rows[0]) throw new Error('Esa pestaña ya no existe');
  if (rows[0].tipo !== 'imagen') throw new Error('Esa pestaña es de texto, no admite carteles');
  const orden = Number.isFinite(entrada.orden) ? Math.round(entrada.orden) : 0;
  const carteles = [await prepararCartel(entrada.provocacion), await prepararCartel(entrada.respuesta)];
  const ids: number[] = [];
  for (const [i, tipo] of (['mensaje', 'respuesta'] as const).entries()) {
    const id = await filaDeMensaje(db, entrada.pestanaId, tipo, nombre, orden);
    await db.query(
      `INSERT INTO vacile_imagenes (mensaje_id, png, jpg, version) VALUES ($1, $2, $3, $4)
       ON CONFLICT (mensaje_id) DO UPDATE SET png = EXCLUDED.png, jpg = EXCLUDED.jpg, version = EXCLUDED.version, subido_at = NOW()`,
      [id, carteles[i].png, carteles[i].jpg, carteles[i].version],
    );
    cartelesEnMemoria.set(id, carteles[i]);
    ids.push(id);
  }
  return { mensajeId: ids[0], respuestaId: ids[1] };
}

/** Quita una pareja de la pestaña (se apaga, no se borra: lo enviado se sigue viendo). */
export async function quitarParejaVacile(db: Db, pestanaId: number, nombre: string): Promise<boolean> {
  const { rows } = await db.query(
    `UPDATE vacile_mensajes SET activo = FALSE
      WHERE pestana_id = $1 AND activo AND LOWER(texto) = LOWER($2) RETURNING id`,
    [pestanaId, nombre.replace(/[_\s]+/g, ' ').trim()],
  );
  return rows.length > 0;
}

/** El cartel (`png`) o su miniatura (`jpg`) de un mensaje, o null si no tiene. */
export async function imagenVacile(db: Db, mensajeId: number): Promise<{ png: Buffer; jpg: Buffer; version: string } | null> {
  const ya = cartelesEnMemoria.get(mensajeId);
  if (ya) return ya;
  const { rows } = await db.query('SELECT png, jpg, version FROM vacile_imagenes WHERE mensaje_id = $1', [mensajeId]);
  if (!rows[0]) return null;
  const cartel = { png: rows[0].png as Buffer, jpg: rows[0].jpg as Buffer, version: String(rows[0].version) };
  cartelesEnMemoria.set(mensajeId, cartel);
  return cartel;
}

/** Las direcciones del cartel y la miniatura de un mensaje (relativas; la
 *  ruta les pone delante el servidor). */
export function direccionesDeCartel(id: number, version: string, base = ''): { imagen: string; miniatura: string } {
  return {
    imagen: `${base}${RUTA_IMAGEN_VACILE}${id}.png?v=${version}`,
    miniatura: `${base}${RUTA_IMAGEN_VACILE}${id}-v.jpg?v=${version}`,
  };
}

/** Eliminar desde el panel: se marca, no se borra. Los vaciles ya enviados
 *  con sus mensajes siguen enseñando su texto y su cartel. */
export async function borrarPestanaVaciles(db: Db, id: number): Promise<boolean> {
  const { rows } = await db.query(
    `UPDATE vacile_pestanas SET borrada = TRUE, modo = 'no' WHERE id = $1 AND NOT borrada RETURNING id`, [id],
  );
  return rows.length > 0;
}

/** Todas las pestañas vivas con sus mensajes, para el panel. `base` es lo que
 *  va delante de las direcciones de los carteles (https://servidor). */
export async function pestanasVacilesAdmin(db: Db, base = ''): Promise<PestanaVacile[]> {
  const { rows: pestanas } = await db.query(
    'SELECT id, nombre, orden, modo, tipo FROM vacile_pestanas WHERE NOT borrada ORDER BY orden, id',
  );
  if (pestanas.length === 0) return [];
  const { rows: mensajes } = await db.query(
    `SELECT m.id, m.pestana_id, m.tipo, m.texto, i.version
       FROM vacile_mensajes m
       JOIN vacile_pestanas p ON p.id = m.pestana_id
       LEFT JOIN vacile_imagenes i ON i.mensaje_id = m.id
      WHERE m.activo AND NOT p.borrada
      ORDER BY m.orden, m.id`,
  );
  const mensaje = (m: any): MensajeVacile => ({
    id: Number(m.id), texto: m.texto,
    ...(m.version ? direccionesDeCartel(Number(m.id), String(m.version), base) : {}),
  });
  return pestanas.map((p: any) => ({
    id: Number(p.id), nombre: p.nombre, orden: Number(p.orden), modo: p.modo,
    tipo: (p.tipo === 'imagen' ? 'imagen' : 'texto') as TipoPestana,
    mensajes: mensajes.filter((m: any) => m.pestana_id === p.id && m.tipo === 'mensaje').map(mensaje),
    respuestas: mensajes.filter((m: any) => m.pestana_id === p.id && m.tipo === 'respuesta').map(mensaje),
  }));
}

/** Lo que ve ESTE corredor en el selector: las pestañas encendidas (o en
 *  prueba para él) que tengan algún mensaje. Sin respuestas propias, las
 *  respuestas son los mismos mensajes: así basta con pegar una lista. En las
 *  de imágenes solo van los mensajes que tienen cartel. */
/** Las pestañas DIBUJADAS dentro de la app (Clásicos y Halloween) también
 *  se encienden y apagan desde el panel, en la misma caja que las demás.
 *  Clásicos va siempre; Halloween tiene su interruptor, guardado como un
 *  ajuste del juego con los mismos valores que las pestañas del panel
 *  ('no' / 'prueba:A,B' / 'si'). Mientras nadie lo toque está APAGADA: la
 *  pestaña no sale en el selector (apps 1.11.15 o más nuevas). Es aparte del
 *  interruptor del evento de Halloween (`halloween`), que manda en las
 *  calabazas y en si los mensajes se abren. */
export const AJUSTE_PESTANA_HALLOWEEN = 'pestana_halloween';

export interface PestanasDibujadas {
  /** ¿Le sale a este corredor la pestaña HALLOWEEN en el selector? */
  halloween: boolean;
}

export function pestanasDibujadasPara(
  valorHalloween: string | null | undefined,
  nombre: string | null,
  leToca: (modo: string, nombre: string | null) => boolean,
): PestanasDibujadas {
  return { halloween: leToca(valorHalloween || 'no', nombre) };
}

/** Un valor guardado ('no' / 'prueba:A,B' / 'si') tal y como lo pinta el
 *  panel: el interruptor de tres posiciones y quién lo prueba. */
export function interruptorParaPanel(valor: string | null | undefined): { modo: 'apagado' | 'prueba' | 'todos'; corredores: string } {
  const v = valor || 'no';
  if (v === 'si') return { modo: 'todos', corredores: '' };
  if (v.startsWith('prueba:')) return { modo: 'prueba', corredores: v.slice('prueba:'.length) };
  return { modo: 'apagado', corredores: '' };
}

export async function pestanasVacilesPara(
  db: Db,
  nombre: string | null,
  leToca: (modo: string, nombre: string | null) => boolean,
  base = '',
): Promise<Omit<PestanaVacile, 'modo' | 'orden'>[]> {
  return (await pestanasVacilesAdmin(db, base))
    .map(p => p.tipo === 'imagen'
      ? { ...p, mensajes: p.mensajes.filter(m => m.imagen), respuestas: p.respuestas.filter(m => m.imagen) }
      : p)
    .filter(p => p.modo !== 'no' && p.mensajes.length > 0 && leToca(p.modo, nombre))
    .map(p => ({
      id: p.id, nombre: p.nombre, tipo: p.tipo, mensajes: p.mensajes,
      respuestas: p.respuestas.length > 0 ? p.respuestas : p.mensajes,
    }));
}
