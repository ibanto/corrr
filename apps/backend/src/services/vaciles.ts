/**
 * Vaciles desde el panel (§9-sexies del CLAUDE.md, 6-nov-2026).
 *
 * Los vaciles de siempre van DIBUJADOS dentro de la app: los Clásicos (ids 1
 * a 10) y los de Halloween (101 a 110), y cada tanda nueva obligaba a sacar
 * versión. Iban: pasar una lista de textos y que salgan en una pestaña nueva
 * del selector sin tocar las tiendas. Así que una pestaña de aquí es un
 * nombre y sus textos; la app pinta cada texto en una tarjeta de CORRR (negro
 * y naranja) en vez de enseñar un dibujo.
 *
 * Los identificadores de los mensajes empiezan en 1001 A PROPÓSITO: el id
 * viaja en la fila de `taunts` y la app de quien lo recibe lo busca primero en
 * sus catálogos dibujados. Si se solaparan con el 1-10 o el 101-110, a quien
 * lo recibiera le saldría el dibujo de ese número en vez del texto.
 *
 * Nada se borra de verdad: un mensaje quitado de la lista se APAGA (`activo`)
 * y una pestaña eliminada se marca (`borrada`). Un vacile ya enviado sigue
 * teniendo su texto cuando el otro abra la app, aunque la pestaña ya no exista.
 */

type Db = { query: (sql: string, params?: any[]) => Promise<{ rows: any[] }> };

/** El primer id de un mensaje del panel. Por debajo están los dibujados. */
export const PRIMER_ID_VACILE = 1001;
/** Tope de mensajes por pestaña y tipo, y de letras por mensaje. En la app el
 *  texto se encoge hasta caber en la tarjeta: más de esto no se lee. */
export const MAX_MENSAJES_VACILE = 50;
export const MAX_LETRAS_VACILE = 140;
export const MAX_NOMBRE_PESTANA = 18;

export type MensajeVacile = { id: number; texto: string };
export type PestanaVacile = {
  id: number;
  nombre: string;
  orden: number;
  /** 'no' / 'si' / 'prueba:Nombre1,Nombre2', como las campañas y Halloween. */
  modo: string;
  mensajes: MensajeVacile[];
  respuestas: MensajeVacile[];
};

export async function prepararVaciles(db: Db): Promise<void> {
  await db.query(`
    CREATE TABLE IF NOT EXISTS vacile_pestanas (
      id SERIAL PRIMARY KEY,
      nombre TEXT NOT NULL,
      orden INT NOT NULL DEFAULT 0,
      modo TEXT NOT NULL DEFAULT 'no',
      borrada BOOLEAN NOT NULL DEFAULT FALSE,
      creada_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await db.query(`
    CREATE TABLE IF NOT EXISTS vacile_mensajes (
      id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH ${PRIMER_ID_VACILE}),
      pestana_id INT NOT NULL REFERENCES vacile_pestanas(id) ON DELETE CASCADE,
      tipo TEXT NOT NULL DEFAULT 'mensaje',
      texto TEXT NOT NULL,
      orden INT NOT NULL DEFAULT 0,
      activo BOOLEAN NOT NULL DEFAULT TRUE,
      creado_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await db.query(`CREATE INDEX IF NOT EXISTS vacile_mensajes_pestana_idx ON vacile_mensajes(pestana_id, tipo) WHERE activo`);
}

/** Lo que se pega en el panel, una línea por mensaje: sin líneas vacías, sin
 *  espacios de más, sin repetidos y con tope. También vale una lista. */
export function lineasDeVaciles(entrada: unknown): string[] {
  const crudo = Array.isArray(entrada) ? entrada.map(x => String(x ?? '')) : String(entrada ?? '').split(/\r?\n/);
  const vistas = new Set<string>();
  const limpias: string[] = [];
  for (const linea of crudo) {
    const texto = linea.replace(/\s+/g, ' ').trim().slice(0, MAX_LETRAS_VACILE).trim();
    if (!texto) continue;
    const clave = texto.toLowerCase();
    if (vistas.has(clave)) continue;
    vistas.add(clave);
    limpias.push(texto);
  }
  return limpias.slice(0, MAX_MENSAJES_VACILE);
}

/** Deja los mensajes de un tipo de una pestaña como dice la lista, sin cambiar
 *  el id de los que siguen: el id es lo que viaja en cada vacile enviado. Un
 *  texto que se quita se apaga; si vuelve a escribirse, revive con su id. */
async function sincronizarMensajes(db: Db, pestanaId: number, tipo: 'mensaje' | 'respuesta', textos: string[]): Promise<void> {
  const { rows: activos } = await db.query(
    'SELECT id, texto FROM vacile_mensajes WHERE pestana_id = $1 AND tipo = $2 AND activo',
    [pestanaId, tipo],
  );
  const idPorTexto = new Map<string, number>(activos.map((r: any) => [String(r.texto).toLowerCase(), Number(r.id)]));
  const seQuedan = new Set<number>();
  for (let i = 0; i < textos.length; i++) {
    const texto = textos[i];
    const ya = idPorTexto.get(texto.toLowerCase());
    if (ya !== undefined) {
      seQuedan.add(ya);
      await db.query('UPDATE vacile_mensajes SET orden = $2, texto = $3 WHERE id = $1', [ya, i, texto]);
      continue;
    }
    const { rows: apagado } = await db.query(
      `SELECT id FROM vacile_mensajes
        WHERE pestana_id = $1 AND tipo = $2 AND NOT activo AND LOWER(texto) = LOWER($3)
        ORDER BY id LIMIT 1`,
      [pestanaId, tipo, texto],
    );
    if (apagado[0]) {
      seQuedan.add(Number(apagado[0].id));
      await db.query('UPDATE vacile_mensajes SET activo = TRUE, orden = $2, texto = $3 WHERE id = $1', [apagado[0].id, i, texto]);
    } else {
      await db.query(
        'INSERT INTO vacile_mensajes (pestana_id, tipo, texto, orden) VALUES ($1, $2, $3, $4)',
        [pestanaId, tipo, texto, i],
      );
    }
  }
  for (const r of activos) {
    if (!seQuedan.has(Number(r.id))) {
      await db.query('UPDATE vacile_mensajes SET activo = FALSE WHERE id = $1', [r.id]);
    }
  }
}

export async function guardarPestanaVaciles(db: Db, entrada: {
  id: number | null;
  nombre: string;
  orden: number;
  modo: string;
  mensajes: string[];
  respuestas: string[];
}): Promise<PestanaVacile> {
  const nombre = entrada.nombre.replace(/\s+/g, ' ').trim().slice(0, MAX_NOMBRE_PESTANA).trim();
  if (!nombre) throw new Error('Falta el nombre de la pestaña');
  if (entrada.mensajes.length === 0) throw new Error('Pon al menos un mensaje, uno por línea');
  const orden = Number.isFinite(entrada.orden) ? Math.round(entrada.orden) : 0;
  let id = entrada.id;
  if (id !== null) {
    const { rows } = await db.query(
      'UPDATE vacile_pestanas SET nombre = $2, orden = $3, modo = $4 WHERE id = $1 AND NOT borrada RETURNING id',
      [id, nombre, orden, entrada.modo],
    );
    if (!rows[0]) throw new Error('Esa pestaña ya no existe');
  } else {
    const { rows } = await db.query(
      'INSERT INTO vacile_pestanas (nombre, orden, modo) VALUES ($1, $2, $3) RETURNING id',
      [nombre, orden, entrada.modo],
    );
    id = Number(rows[0].id);
  }
  await sincronizarMensajes(db, id, 'mensaje', entrada.mensajes);
  await sincronizarMensajes(db, id, 'respuesta', entrada.respuestas);
  const guardada = (await pestanasVacilesAdmin(db)).find(p => p.id === id);
  if (!guardada) throw new Error('No se ha podido guardar la pestaña');
  return guardada;
}

/** Eliminar desde el panel: se marca, no se borra. Los vaciles ya enviados
 *  con sus mensajes siguen enseñando su texto. */
export async function borrarPestanaVaciles(db: Db, id: number): Promise<boolean> {
  const { rows } = await db.query(
    `UPDATE vacile_pestanas SET borrada = TRUE, modo = 'no' WHERE id = $1 AND NOT borrada RETURNING id`, [id],
  );
  return rows.length > 0;
}

/** Todas las pestañas vivas con sus mensajes, para el panel. */
export async function pestanasVacilesAdmin(db: Db): Promise<PestanaVacile[]> {
  const { rows: pestanas } = await db.query(
    'SELECT id, nombre, orden, modo FROM vacile_pestanas WHERE NOT borrada ORDER BY orden, id',
  );
  if (pestanas.length === 0) return [];
  const { rows: mensajes } = await db.query(
    `SELECT m.id, m.pestana_id, m.tipo, m.texto
       FROM vacile_mensajes m JOIN vacile_pestanas p ON p.id = m.pestana_id
      WHERE m.activo AND NOT p.borrada
      ORDER BY m.orden, m.id`,
  );
  return pestanas.map((p: any) => ({
    id: Number(p.id), nombre: p.nombre, orden: Number(p.orden), modo: p.modo,
    mensajes: mensajes.filter((m: any) => m.pestana_id === p.id && m.tipo === 'mensaje')
      .map((m: any) => ({ id: Number(m.id), texto: m.texto })),
    respuestas: mensajes.filter((m: any) => m.pestana_id === p.id && m.tipo === 'respuesta')
      .map((m: any) => ({ id: Number(m.id), texto: m.texto })),
  }));
}

/** Lo que ve ESTE corredor en el selector: las pestañas encendidas (o en
 *  prueba para él) que tengan algún mensaje. Sin respuestas propias, las
 *  respuestas son los mismos mensajes: así basta con pegar una lista. */
export async function pestanasVacilesPara(
  db: Db,
  nombre: string | null,
  leToca: (modo: string, nombre: string | null) => boolean,
): Promise<Omit<PestanaVacile, 'modo' | 'orden'>[]> {
  return (await pestanasVacilesAdmin(db))
    .filter(p => p.modo !== 'no' && p.mensajes.length > 0 && leToca(p.modo, nombre))
    .map(p => ({
      id: p.id, nombre: p.nombre, mensajes: p.mensajes,
      respuestas: p.respuestas.length > 0 ? p.respuestas : p.mensajes,
    }));
}
