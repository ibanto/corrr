/** Una frase al azar para la tarjeta. Si no hubo robo se descartan los tonos
 *  que dan por hecho que le has quitado algo a alguien ("gracias por
 *  cuidármelo" no pega si conquistaste terreno virgen). */
export function randomSharePhrase(hasSteals: boolean): string {
  const pool = GROUPS.filter(g => hasSteals || !STEAL_ONLY_CATEGORIES.includes(g.category));
  const all = pool.flatMap(g => g.phrases);
  return all[Math.floor(Math.random() * all.length)];
}
